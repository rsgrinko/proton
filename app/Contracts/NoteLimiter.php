<?php

declare(strict_types=1);

namespace App\Contracts;

/**
 * Проверка лимита заметок на пользователя.
 *
 * Интерфейс — пример того, зачем нужна привязка в config/services.php:
 * контроллер просит проверку по типу, а какая она внутри (по настройке,
 * по тарифу, всегда без ограничений) решает привязка, а не вызывающий код.
 */
interface NoteLimiter
{
    /**
     * Заведено уже столько, что новую заметку создавать нельзя?
     */
    public function exceeded(int $userId): bool;
}

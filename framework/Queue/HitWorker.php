<?php

declare(strict_types=1);

namespace Rsgrinko\Proton\Queue;

use Rsgrinko\Proton\Support\Config;
use Rsgrinko\Proton\Support\Logger;
use Throwable;

/**
 * Разбор очереди прямо на HTTP-запросе — для тех, у кого нет (или не всегда
 * есть) отдельного демона-воркера: дешёвый хостинг без systemd, разработка
 * без второго терминала, подстраховка на случай, если служба воркера упала,
 * а перезапустить её быстро некому.
 *
 * Включается явно (`QUEUE_PROCESS_ON_HIT=true`) — по умолчанию выключено:
 * это подстраховка, а не замена настоящему воркеру, и должна быть осознанным
 * решением, а не сюрпризом после обновления фреймворка. Отдельного демона
 * это не отменяет: без единого хита за час (глубокая ночь) не разберётся
 * и очередь.
 *
 * Разбор идёт прямо в запросе, до ответа клиенту: без систем вроде php-fpm
 * нет надёжного способа продолжить работу уже после ответа, а плодить его
 * только на одном SAPI — усложнять то, что должно быть простой подстраховкой.
 */
final class HitWorker
{
    public static function run(): void
    {
        if (!(bool) Config::get('queue.process_on_hit', false)) {
            return;
        }

        try {
            (new Worker())->run(true);
        } catch (Throwable $e) {
            (new Logger('worker'))->error('Разбор очереди на хите не задался', ['error' => $e->getMessage()]);
        }
    }
}

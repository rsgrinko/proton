<?php

declare(strict_types=1);

/**
 * Входящие вебхуки: кого мы готовы слушать.
 *
 * Адрес источника — POST /api/v1/hooks/{ключ}. Ключ подписи берётся не отсюда,
 * а из окружения по имени переменной: секрет чужой системы в репозитории делать
 * нечего. Источник без секрета принимается как есть — так бывает у систем,
 * которые подписывать не умеют.
 *
 * Обработчик получает разобранное тело и сам запрос. Долгую работу из него
 * лучше отправлять в очередь: чужая система ждёт ответа и повторит посылку,
 * если мы будем думать слишком долго.
 */

use Rsgrinko\Proton\Http\Request;
use Rsgrinko\Proton\Support\Logger;
use Rsgrinko\Proton\Webhooks\Incoming;

// Пример: эхо-источник для проверки связи. Подпись обязательна, секрет лежит
// в переменной окружения DEMO_HOOK_SECRET
Incoming::register('demo', 'Демонстрационный источник', 'DEMO_HOOK_SECRET', static function (array $payload, Request $request): void {
    (new Logger('webhooks'))->info('Пришёл демонстрационный вебхук', [
        'event' => (string) ($payload['event'] ?? ''),
        'ip'    => $request->ip(),
    ]);
});
